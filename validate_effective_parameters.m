function validate_effective_parameters(P)
%VALIDATE_EFFECTIVE_PARAMETERS
% Does not change EOS maps, phase ownership, heat laws or parameter values.

validateattributes(P, {'struct'}, {'scalar'}, mfilename, 'P');

positive = {'VTotal1','VTotal2','R1','R2','A1','A2','Lcyl','H', ...
    'p10','p20','TL10','TL20','Tv10','Tv20','Ts10','Ts20','Tw20', ...
    'rho_L','rhoL10','rhov10','rhoL20','rhov20', ...
    'totalmass10','mL10','mv10','mL20','mv20','mw2', ...
    'c_L','c_p','c_v','T_c','p_c','lambda', ...
    'tminL1','tminV1','tminL2','tminV2','tau_tr','tau_vap', ...
    'DPipe','LPipe','drPipe','dE','kE','f', ...
    'S_valve1','S_valve2','relTol','tFinal'};

for k = 1:numel(positive)
    name = positive{k};
    if ~isfield(P,name)
        error('LH2:MissingEffectiveParameter', ...
            'Missing effective parameter P.%s.', name);
    end
    validateattributes(P.(name), {'numeric'}, ...
        {'real','finite','scalar','positive'}, mfilename, name);
end

for name = {'nL1','nV1','nL2','nV2'}
    validateattributes(P.(name{1}), {'numeric'}, ...
        {'real','finite','scalar','integer','>=',2}, ...
        mfilename, name{1});
end

% A component buffer may start empty.
validateattributes(P.mVap0, {'numeric'}, ...
    {'real','finite','scalar','nonnegative'}, mfilename, 'mVap0');

% Zero disables these coefficients; signed heat inputs remain permissible.
for name = {'c_vap','STBoiloffrate','ETBoiloffrate'}
    validateattributes(P.(name{1}), {'numeric'}, ...
        {'real','finite','scalar','nonnegative'}, ...
        mfilename, name{1});
end
for name = {'QdotEL1','QdotEV1','QdotEW2'}
    validateattributes(P.(name{1}), {'numeric'}, ...
        {'real','finite','scalar'}, mfilename, name{1});
end

validateattributes(P.Vullage10, {'numeric'}, ...
    {'real','finite','scalar','positive','<',P.VTotal1}, ...
    mfilename, 'Vullage10');
validateattributes(P.VL20, {'numeric'}, ...
    {'real','finite','scalar','positive','<',P.VTotal2}, ...
    mfilename, 'VL20');
validateattributes(P.hL20, {'numeric'}, ...
    {'real','finite','scalar','positive','<',P.H}, ...
    mfilename, 'hL20');

for name = {'p_ET_low','p_ET_high'}
    validateattributes(P.(name{1}), {'numeric'}, ...
        {'real','finite','scalar','positive'}, ...
        mfilename, name{1});
end
assert(P.p_ET_low <= P.p_ET_high, ...
    'LH2:InvalidEffectivePressure', ...
    'Require p_ET_low <= p_ET_high.');
end