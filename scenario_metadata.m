function info = scenario_metadata(caseNumber)
%SCENARIO_METADATA Shared scenario identity for initialization and exports.
validateattributes(caseNumber, {'numeric'}, {'real','finite','scalar','integer','>=',1,'<=',8}, ...
    mfilename, 'Case');
names = ["Original-TrailerToMain", "TrailerToMainPressureDiff", ...
    "TrailerToMainPump", "MainToOnboardPressureDiff", "MainToOnboardPump", ...
    "ExternalTankInitialBlowdown", "CustomPressureDiff", "CustomPump"];
scenarios = ["Original", "Trailer to Main", "Trailer to Main", ...
    "Main to On-board", "Main to On-board", "External tank initial blowdown", ...
    "Custom pressure-driven transfer", "Custom pump-driven transfer"];
files = ["Parameters_Original", "Parameters_TrailerToMain_PressDiff", ...
    "Parameters_TrailerToMain_Pump", "Parameters_MainToOnboard_PressDiff", ...
    "Parameters_MainToOnboard_Pump", "Parameters_TrailerToMain_Pump_InitialBlowdown_PlugPower", ...
    "Parameters_Custom_PressDiff", "Parameters_Custom_Pump"];
info.name = names(caseNumber);
info.Scenario = scenarios(caseNumber);
info.parameterFile = files(caseNumber);
info.isPump = any(caseNumber == [3 5 6 8]);
if info.isPump
    info.Method = "Pump";
else
    info.Method = "Pres. diff.";
end
end
